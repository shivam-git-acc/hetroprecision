"""Build results/HEAD_RESULTS.md: every measured value, per task, per layer and head, from the result CSVs.

Usage (from the project root): python3 scripts/make_results_md.py
"""
import csv
import os
from collections import defaultdict

RES = "results"
OUT = os.path.join(RES, "HEAD_RESULTS.md")
TASKS = ["lm", "needle", "gsm8k"]
TASK_NAMES = {"lm": "Language modeling (WikiText-2)", "needle": "Needle retrieval (passkey, 8K)",
              "gsm8k": "GSM8K reasoning (teacher-forced)"}
L, HKV, HQ = 28, 4, 28


def fmt(x, nd=4):
    if x is None or x == "":
        return ""
    x = float(x)
    if x != x:  # nan
        return ""
    if x == 0:
        return "0"
    if abs(x) < 10 ** -nd:
        return f"{x:.1e}"
    return f"{x:.{nd}f}"


def grid(values, n_cols, col_label, nd=4, bold_top=0):
    """values: {(layer, col): float}. One row per layer, one column per head."""
    top = set(sorted(values, key=lambda k: -values[k])[:bold_top]) if bold_top else set()
    lines = ["| layer | " + " | ".join(f"{col_label}{c}" for c in range(n_cols)) + " |",
             "|---" * (n_cols + 1) + "|"]
    for layer in range(L):
        cells = []
        for c in range(n_cols):
            v = values.get((layer, c))
            s = fmt(v, nd)
            cells.append(f"**{s}**" if (layer, c) in top else s)
        lines.append(f"| {layer} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main():
    out = []
    w = out.append
    w("# Per-head results: Qwen2.5-7B-Instruct\n")
    w("Generated by `scripts/make_results_md.py` from the CSV files in `results/`. Every value is as measured; "
      "regenerate after new runs. Context and method: `results/NOTES.md`.\n")
    w("Model shape: 28 layers × 28 query heads × 4 KV heads (7 query heads share each KV head). "
      "`Lx.kvy` = layer x, KV head y. Query head q belongs to KV head q // 7.\n")
    w("## Contents\n")
    w("1. Sensitivity: KL divergence per KV head, per task, per quantization config")
    w("2. Needle accuracy per KV head")
    w("3. Bit-allocation results on held-out data")
    w("4. Attention statistics per query head (retrieval, entropy, sink, local)")
    w("5. Key outlier ratio per KV head\n")

    # ------------------------------------------------------------- 1 + 2 sensitivity
    sens_path = os.path.join(RES, "sens_qwen7b.csv")
    if os.path.exists(sens_path):
        rows = list(csv.DictReader(open(sens_path)))
        configs = []
        for r in rows:
            c = (r["bits"], r["scheme"])
            if c not in configs:
                configs.append(c)
        w("## 1. Sensitivity: KL(BF16 ‖ one KV head quantized)\n")
        w("Method: fake-quantize K and V of one KV head (post-RoPE, inside attention), all other heads BF16. "
          "Value = mean KL divergence of the next-token distribution vs BF16 over scored tokens. "
          "Higher = more sensitive. **Bold** = top 5 in that table. "
          "Calibration data: WikiText-2 train 8×4K (last 512 tokens scored), needle 8×8K (answer tokens), "
          "GSM8K train 16 (solution tokens).\n")
        w("Schemes: `token` = asymmetric min-max per token over the 128-dim head vector (K and V); "
          "`kivi` = K per channel over groups of 128 tokens, V per token.\n")
        for bits, scheme in configs:
            sub = [r for r in rows if r["bits"] == bits and r["scheme"] == scheme]
            n_heads_done = len({(r["layer"], r["kv_head"]) for r in sub if r["layer"] != "-1"})
            w(f"### {bits}-bit, scheme `{scheme}` ({n_heads_done}/112 heads measured)\n")
            allq = {r["task"]: r for r in sub if r["layer"] == "-1"}
            if allq:
                w("All 112 KV heads quantized at once (reference): " + "; ".join(
                    f"{t} KL = {fmt(allq[t]['kl'])}" + (f", needle acc = {fmt(allq[t]['acc'], 2)}" if t == "needle" else "")
                    for t in TASKS if t in allq) + "\n")
            for t in TASKS:
                vals = {(int(r["layer"]), int(r["kv_head"])): float(r["kl"]) for r in sub
                        if r["task"] == t and r["layer"] != "-1"}
                if not vals:
                    continue
                ranked = sorted(vals, key=lambda k: -vals[k])
                total = sum(vals.values())
                w(f"#### {TASK_NAMES[t]}: {bits}-bit `{scheme}`\n")
                w("Top 10: " + ", ".join(f"L{l}.kv{h} = {fmt(vals[(l, h)])}" for l, h in ranked[:10]) + "\n")
                layer_share = {l: sum(vals.get((l, h), 0) for h in range(HKV)) / total for l in range(L)} if total else {}
                if layer_share:
                    w("Share of summed KL by layer (top 5): " + ", ".join(
                        f"L{l} {v:.1%}" for l, v in sorted(layer_share.items(), key=lambda x: -x[1])[:5]) + "\n")
                w(grid(vals, HKV, "kv", nd=4, bold_top=5) + "\n")
            acc = {(int(r["layer"]), int(r["kv_head"])): float(r["acc"]) for r in sub
                   if r["task"] == "needle" and r["layer"] != "-1"}
            if acc:
                w(f"#### Needle exact-match accuracy with one KV head quantized: {bits}-bit `{scheme}`\n")
                drops = sorted((k for k, a in acc.items() if a < 1), key=lambda k: acc[k])
                w("Heads where accuracy drops below 1.00 (BF16 = 1.00): " +
                  (", ".join(f"L{l}.kv{h} = {acc[(l, h)]:.3f}" for l, h in drops) if drops else "none") + "\n")
                w(grid(acc, HKV, "kv", nd=3) + "\n")

    # ------------------------------------------------------------- 3 allocation
    alloc_path = os.path.join(RES, "alloc_qwen7b.csv")
    if os.path.exists(alloc_path):
        rows = list(csv.DictReader(open(alloc_path)))
        w("## 3. Bit allocations on held-out data\n")
        w("Held-out: WikiText-2 test 16×4K (last 512 tokens), needle seed 123 16×8K, GSM8K test 16. "
          "One combined ranking for all tasks (max over tasks of head KL / task max, 2-bit `token` sweep). "
          "Protected top 5 = L0.kv0, L0.kv1, L0.kv2, L27.kv1, L0.kv3. "
          "Random-5 control = L27.kv0, L12.kv1, L24.kv1, L13.kv1, L1.kv1. "
          "Avg bits include one FP16 scale + zero-point per 128 values.\n")
        by = defaultdict(dict)
        order = []
        for r in rows:
            if r["allocation"] not in order:
                order.append(r["allocation"])
            by[r["allocation"]][r["task"]] = r
        w("| allocation | avg bits | LM KL | LM ppl | needle KL | needle acc | GSM8K KL | GSM8K ppl |")
        w("|---|---|---|---|---|---|---|---|")
        for a in order:
            d = by[a]
            w(f"| {a} | {fmt(d['lm']['avg_bits'], 2)} | {fmt(d['lm']['kl'])} | {fmt(d['lm']['ppl'], 2)} | "
              f"{fmt(d['needle']['kl'])} | {fmt(d['needle']['acc'], 3)} | {fmt(d['gsm8k']['kl'])} | "
              f"{fmt(d['gsm8k']['ppl'], 2)} |")
        w("")

    # ------------------------------------------------------------- 4 + 5 attention stats
    st_path = os.path.join(RES, "stats_qwen7b.csv")
    if os.path.exists(st_path):
        rows = list(csv.DictReader(open(st_path)))
        w("## 4. Attention statistics per query head (BF16, no quantization)\n")
        w("8 samples per task (seed 1). Rows analysed: LM = last 128 positions of 4K windows; needle = positions "
          "predicting the passkey digits; GSM8K = positions predicting the solution. "
          "Columns `q0`–`q27` are query heads; q0–q6 → kv0, q7–q13 → kv1, q14–q20 → kv2, q21–q27 → kv3.\n")
        metrics = [
            ("retrieval", ["needle"], "Retrieval score: fraction of answer rows whose top-1 key is the passkey digit being copied (Wu et al., 2024)", 2),
            ("needle_mass", ["needle"], "Attention mass on the passkey digits at answer rows", 2),
            ("entropy", TASKS, "Attention entropy (nats)", 2),
            ("sink4", TASKS, "Attention mass on the first 4 tokens (attention sink)", 2),
            ("local", TASKS, "Attention mass on the 64 most recent tokens", 2),
        ]
        for m, tasks, desc, nd in metrics:
            for t in tasks:
                vals = {(int(r["layer"]), int(r["q_head"])): float(r[m]) for r in rows
                        if r["task"] == t and r.get(m) not in (None, "")}
                if not vals:
                    continue
                w(f"### {desc}: {TASK_NAMES[t]}\n")
                if m == "retrieval":
                    top = sorted(vals, key=lambda k: -vals[k])[:10]
                    w("Top 10: " + ", ".join(f"L{l}.q{h} (kv{h // 7}) = {vals[(l, h)]:.2f}" for l, h in top) + "\n")
                w(grid(vals, HQ, "q", nd=nd, bold_top=10 if m in ("retrieval", "needle_mass") else 0) + "\n")

    k_path = os.path.join(RES, "stats_qwen7b_keys.csv")
    if os.path.exists(k_path):
        rows = list(csv.DictReader(open(k_path)))
        w("## 5. Key outlier ratio per KV head\n")
        w("max over channels of mean |K| / median over channels of mean |K| (post-RoPE keys). "
          "Large = a few channels dominate, so a per-token scale wastes most quantization levels. **Bold** = top 5.\n")
        for t in TASKS:
            vals = {(int(r["layer"]), int(r["kv_head"])): float(r["key_outlier"]) for r in rows if r["task"] == t}
            if vals:
                w(f"### {TASK_NAMES[t]}\n")
                w(grid(vals, HKV, "kv", nd=1, bold_top=5) + "\n")

    with open(OUT, "w") as f:
        f.write("\n".join(out))
    print(f"wrote {OUT} ({len(out)} blocks)")


if __name__ == "__main__":
    main()
