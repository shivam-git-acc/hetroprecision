"""Generate real text under several KV-cache quantization settings, side by side.

Each setting fake-quantizes the KV cache inside attention (same hook as the sensitivity / allocation
experiments, per-token scheme), during both prefill and every decode step. Greedy decoding, so any
difference from BF16 comes from the KV quantization alone.

Output: a markdown file with the prompt (needle prompt abbreviated), the true answer where there is one,
and each setting's generated text.

Usage: python gen_examples.py --out ../results/GENERATION_EXAMPLES.md
"""
import argparse
import random
import time

import torch
from datasets import load_dataset
from transformers import AutoModelForCausalLM, AutoTokenizer

import head_sensitivity as hs

TOP5 = [(0, 0), (0, 1), (0, 2), (27, 1), (0, 3)]          # combined sensitivity ranking, 2-bit per-token sweep
RANDOM5 = [(27, 0), (12, 1), (24, 1), (13, 1), (1, 1)]    # control used in alloc_eval.py (random.Random(0))


def alloc(protect, rest_bits, n_layers, n_kv):
    return {(l, h): (16 if (l, h) in protect else rest_bits) for l in range(n_layers) for h in range(n_kv)}


@torch.inference_mode()
def generate(model, tok, ids, max_new):
    out = model.generate(ids.cuda(), max_new_tokens=max_new, do_sample=False, use_cache=True,
                         pad_token_id=tok.eos_token_id)
    return tok.decode(out[0, ids.shape[1]:], skip_special_tokens=True).strip()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="Qwen/Qwen2.5-7B-Instruct")
    ap.add_argument("--out", default="GENERATION_EXAMPLES.md")
    ap.add_argument("--kivi", action="store_true",
                    help="KIVI-style settings instead: keys per-channel, values per-token, 128-token BF16 residual")
    args = ap.parse_args()

    tok = AutoTokenizer.from_pretrained(args.model)
    model = AutoModelForCausalLM.from_pretrained(args.model, dtype=torch.bfloat16, device_map="cuda",
                                                 attn_implementation="sdpa").eval()
    L, H = model.config.num_hidden_layers, model.config.num_key_value_heads
    hs.QCFG.scheme = "kivi" if args.kivi else "token"

    settings = [
        ("BF16 (reference)", None, 16.0),
        ("KIVI uniform 4-bit (all 112 KV heads)", alloc([], 4, L, H), 4.25),
        ("KIVI uniform 2-bit (all 112 KV heads)", alloc([], 2, L, H), 2.25),
        ("KIVI top-5 heads BF16, rest 2-bit", alloc(TOP5, 2, L, H), 2.86),
    ] if args.kivi else [
        ("BF16 (reference)", None, 16.0),
        ("Uniform 4-bit (all 112 KV heads)", alloc([], 4, L, H), 4.25),
        ("Top-5 sensitive heads BF16, rest 4-bit", alloc(TOP5, 4, L, H), 4.77),
        ("Random-5 heads BF16, rest 2-bit (control)", alloc(RANDOM5, 2, L, H), 2.86),
    ]

    # prompts
    prompts = []
    ids, n_ans, ans = hs.needle_samples(tok, 1, 8192, 123)[0]
    needle_prompt = ids[:, :-n_ans]  # drop the appended answer; the model must generate it
    prompts.append(("Needle retrieval (8K-token document, passkey hidden inside)", needle_prompt, tok.decode(ans), 16,
                    "[~8,000 tokens of WikiText with the sentence \"The secret passkey is " + tok.decode(ans) +
                    ". Remember it.\" inserted]  What is the secret passkey mentioned in the text above? "
                    "Answer with the number only."))
    ex = load_dataset("openai/gsm8k", "main", split="test")[7]
    g_ids = tok.apply_chat_template([{"role": "user", "content": ex["question"]}], add_generation_prompt=True,
                                    return_tensors="pt", return_dict=True)["input_ids"]
    prompts.append(("GSM8K math word problem (test set, #7)", g_ids, ex["answer"].split("####")[-1].strip(), 320,
                    ex["question"]))
    q = "Explain in three sentences what a KV cache is in a transformer and why it matters for long contexts."
    f_ids = tok.apply_chat_template([{"role": "user", "content": q}], add_generation_prompt=True,
                                    return_tensors="pt", return_dict=True)["input_ids"]
    prompts.append(("Free-text question", f_ids, None, 160, q))

    lines = ["# Generation examples: what KV-cache quantization does to the output",
             "",
             f"Model: {args.model}, greedy decoding. Generated by `scripts/gen_examples.py` on "
             f"{time.strftime('%Y-%m-%d %H:%M')}. KV cache fake-quantized inside attention (per-token, asymmetric "
             "min-max; with --kivi: keys per channel), during prefill and every decode step. Only the KV cache differs between settings.",
             "",
             "Top-5 sensitive KV heads (from the sensitivity sweep): " + ", ".join(f"L{l}.kv{h}" for l, h in TOP5) +
             ". Random-5 control: " + ", ".join(f"L{l}.kv{h}" for l, h in RANDOM5) + ".",
             "",
             "| Setting | Avg bits per KV value |", "|---|---|"]
    lines += [f"| {name} | {bits} |" for name, _, bits in settings]
    lines.append("")

    for title, p_ids, truth, max_new, shown in prompts:
        lines += [f"## {title}", "", f"**Prompt ({p_ids.shape[1]} tokens):** {shown}", ""]
        if truth is not None:
            lines += [f"**Correct answer:** {truth}", ""]
        for name, a, _ in settings:
            hs.QCFG.alloc = a or {}
            hs.QCFG.target = "alloc" if a else None
            t0 = time.time()
            text = generate(model, tok, p_ids, max_new)
            hs.QCFG.target = None
            verdict = ""
            if truth is not None:
                verdict = " ✅ correct" if truth.replace(",", "") in text.replace(",", "") else " ❌ wrong"
            print(f"[{title[:20]}] {name}: {verdict} {text[:80]!r} ({time.time() - t0:.1f}s)", flush=True)
            lines += [f"### {name}{verdict}", "", "```text", text, "```", ""]
        with open(args.out, "w") as f:  # rewrite after each prompt so partial results survive
            f.write("\n".join(lines))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
